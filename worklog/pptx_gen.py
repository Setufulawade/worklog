"""Create a .pptx from deck content using python-pptx."""

import copy  # noqa: F401  (kept for easy extension)

from .reports import stats_text  # noqa: F401

NAVY = (0x14, 0x21, 0x3D)
ACCENT = (0x2A, 0x9D, 0x8F)
INK = (0x22, 0x2B, 0x38)
MUTED = (0x6B, 0x76, 0x85)
PAPER = (0xFA, 0xFB, 0xFC)
WHITE = (0xFF, 0xFF, 0xFF)


def _import():
    try:
        from pptx import Presentation
        from pptx.dml.color import RGBColor
        from pptx.enum.shapes import MSO_SHAPE
        from pptx.enum.text import MSO_ANCHOR, PP_ALIGN
        from pptx.util import Emu, Inches, Pt
    except ImportError:
        raise SystemExit(
            "PPT export needs the python-pptx library.\n"
            "  Debian/Ubuntu:  sudo apt install python3-pptx\n"
            "  or:             pip install python-pptx"
        ) from None
    return Presentation, RGBColor, MSO_SHAPE, MSO_ANCHOR, PP_ALIGN, Emu, Inches, Pt


def _rect(slide, MSO_SHAPE, RGBColor, x, y, w, h, color):
    shp = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, x, y, w, h)
    shp.fill.solid()
    shp.fill.fore_color.rgb = RGBColor(*color)
    shp.line.fill.background()
    shp.shadow.inherit = False
    return shp


def _text(slide, x, y, w, h, text, size, color, Pt, RGBColor, bold=False, anchor=None, align=None):
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    if anchor is not None:
        tf.vertical_anchor = anchor
    p = tf.paragraphs[0]
    if align is not None:
        p.alignment = align
    r = p.add_run()
    r.text = text
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.name = "Calibri"
    r.font.color.rgb = RGBColor(*color)
    return tb


def _bullet(paragraph, level_indent_emu=285750):
    """Turn a paragraph into a real bullet with hanging indent."""
    from pptx.oxml.ns import qn
    from lxml import etree

    pPr = paragraph._p.get_or_add_pPr()
    pPr.set("marL", str(level_indent_emu))
    pPr.set("indent", str(-level_indent_emu))
    for tag in ("a:buNone", "a:buChar", "a:buAutoNum"):
        for el in pPr.findall(qn(tag)):
            pPr.remove(el)
    bu = etree.SubElement(pPr, qn("a:buChar"))
    bu.set("char", "•")


def _font_size(bullets):
    n = len(bullets)
    longest = max((len(b) for b in bullets), default=0)
    total = sum(len(b) for b in bullets)
    size = 28 if (n <= 4 and total <= 260) else 24
    if n > 5 or total > 380:
        size = 20
    if n > 7 or total > 560 or longest > 120:
        size = 17
    if total > 800:
        size = 15
    return size


def build(path, label, stats, deck, kind):
    (Presentation, RGBColor, MSO_SHAPE, MSO_ANCHOR, PP_ALIGN, Emu, Inches, Pt) = _import()

    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    blank = prs.slide_layouts[6]
    W, H = prs.slide_width, prs.slide_height

    def background(slide, color):
        bg = slide.background.fill
        bg.solid()
        bg.fore_color.rgb = RGBColor(*color)

    # ---- title slide
    s = prs.slides.add_slide(blank)
    background(s, NAVY)
    _rect(s, MSO_SHAPE, RGBColor, Inches(0.9), Inches(2.55), Inches(1.2), Inches(0.08), ACCENT)
    _text(s, Inches(0.8), Inches(2.7), Inches(11.5), Inches(1.6), deck["title"], 44, WHITE, Pt, RGBColor, bold=True)
    _text(s, Inches(0.8), Inches(4.2), Inches(11.5), Inches(0.8), deck.get("subtitle", label), 24, (0xB8, 0xC4, 0xD6), Pt, RGBColor)
    _text(s, Inches(0.8), Inches(6.5), Inches(8), Inches(0.5), "Generated by worklog", 14, (0x8A, 0x98, 0xAE), Pt, RGBColor)

    # ---- stats slide
    s = prs.slides.add_slide(blank)
    background(s, PAPER)
    _rect(s, MSO_SHAPE, RGBColor, 0, 0, Inches(0.25), H, ACCENT)
    _text(s, Inches(0.9), Inches(0.6), Inches(11.5), Inches(1), f"{label} at a glance", 34, NAVY, Pt, RGBColor, bold=True)
    busiest = f"{stats['busiest_day']:%d %b}" if stats["busiest_day"] else "-"
    cards = [
        (str(stats["days_logged"]), f"days logged of {stats['days_in_period']}"),
        (str(stats["entries"]), "log entries"),
        (str(stats["longest_streak"]), "day longest streak"),
        (busiest, f"busiest day ({stats['busiest_count']} entries)"),
    ]
    cw, gap = Inches(2.7), Inches(0.3)
    x0 = Inches(0.9)
    for i, (big, small) in enumerate(cards):
        x = x0 + i * (cw + gap)
        _rect(s, MSO_SHAPE, RGBColor, x, Inches(2.4), cw, Inches(2.6), WHITE)
        _rect(s, MSO_SHAPE, RGBColor, x, Inches(2.4), cw, Inches(0.08), ACCENT)
        _text(s, x, Inches(2.9), cw, Inches(1.2), big, 54, NAVY, Pt, RGBColor, bold=True, align=PP_ALIGN.CENTER)
        _text(s, x + Inches(0.1), Inches(4.1), cw - Inches(0.2), Inches(0.8), small, 16, MUTED, Pt, RGBColor, align=PP_ALIGN.CENTER)

    # ---- content slides
    total = len(deck["slides"])
    for idx, sl in enumerate(deck["slides"], 1):
        s = prs.slides.add_slide(blank)
        background(s, PAPER)
        _rect(s, MSO_SHAPE, RGBColor, 0, 0, Inches(0.25), H, ACCENT)
        _text(s, Inches(0.9), Inches(0.55), Inches(11.5), Inches(1), str(sl.get("title", "")), 32, NAVY, Pt, RGBColor, bold=True)
        _rect(s, MSO_SHAPE, RGBColor, Inches(0.95), Inches(1.5), Inches(0.9), Inches(0.05), ACCENT)

        bullets = [str(b) for b in sl["bullets"]]
        size = _font_size(bullets)
        tb = s.shapes.add_textbox(Inches(0.9), Inches(1.85), Inches(11.5), Inches(4.8))
        tf = tb.text_frame
        tf.word_wrap = True
        for i, b in enumerate(bullets):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.space_after = Pt(10)
            _bullet(p)
            r = p.add_run()
            r.text = b
            r.font.size = Pt(size)
            r.font.name = "Calibri"
            r.font.color.rgb = RGBColor(*INK)

        _text(s, Inches(11.4), Inches(6.95), Inches(1.6), Inches(0.4), f"{idx} / {total}", 12, MUTED, Pt, RGBColor, align=PP_ALIGN.RIGHT)
        if sl.get("notes"):
            s.notes_slide.notes_text_frame.text = str(sl["notes"])

    prs.save(str(path))
    return len(prs.slides)
